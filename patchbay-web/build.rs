//! Embeds the SQL migrations (../db/migrations/*.sql) into the binary: `patchbay-web migrate` applies
//! them, so a deployment needs only the image (no checkout of db/).
use std::{env, fs, path::PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let dir = manifest.join("../db/migrations");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut names: Vec<String> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e} (the Docker build must copy db/migrations)", dir.display()))
        .map(|e| e.unwrap().file_name().into_string().expect("migration file name is not UTF-8"))
        .filter(|n| n.ends_with(".sql"))
        .collect();
    names.sort();
    assert!(!names.is_empty(), "no migrations in {}", dir.display());
    let mut out = String::from("/// (file name, SQL), sorted by name (generated by build.rs)\npub static MIGRATIONS: &[(&str, &str)] = &[\n");
    for n in &names {
        assert!(
            n.bytes().all(|b| b.is_ascii_alphanumeric() || b"_.-".contains(&b)),
            "invalid migration file name {n}"
        );
        let path = fs::canonicalize(dir.join(n)).unwrap();
        out += &format!("    ({n:?}, include_str!({:?})),\n", path.display().to_string());
    }
    out += "];\n";
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("migrations.rs"), out).unwrap();
}
