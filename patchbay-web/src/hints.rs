//! Busy lamp fields: writes /generated/hints.conf (one hint per person over all of their active
//! devices) and reloads the dialplan when it changed. It changes exactly when the set of active
//! devices changes, so res_pjsip is reloaded then too: Asterisk sets up the device state of an
//! endpoint (qualify -> online/offline) only for the endpoints it sees at load or reload, a new
//! realtime device would otherwise stay "Unavailable" for hints and queues until a restart.

use std::time::Duration;

use crate::{AppState, ami};

const OUT: &str = "/generated/hints.conf";

async fn render(app: &AppState) -> anyhow::Result<String> {
    let rows: Vec<(i16, String)> = sqlx::query_as(
        "SELECT extension, string_agg('PJSIP/' || sip_username, '&' ORDER BY ring_order, id)
         FROM active_devices GROUP BY extension ORDER BY extension",
    )
    .fetch_all(&app.db)
    .await?;
    let mut out = String::from("; Generated by patchbay-web (busy lamps). Do not edit.\n");
    for (ext, devices) in rows {
        out += &format!("exten => {ext},hint,{devices}\n");
    }
    Ok(out)
}

async fn apply(app: &AppState) -> anyhow::Result<()> {
    let content = render(app).await?;
    if tokio::fs::read_to_string(OUT).await.unwrap_or_default() == content {
        return Ok(());
    }
    let tmp = format!("{OUT}.tmp");
    tokio::fs::write(&tmp, &content).await?;
    tokio::fs::rename(&tmp, OUT).await?;
    ami::command("module reload res_pjsip.so").await?;
    ami::command("dialplan reload").await?;
    Ok(())
}

pub fn spawn(app: AppState) {
    tokio::spawn(async move {
        tokio::time::sleep(Duration::from_secs(20)).await;
        loop {
            if let Err(e) = apply(&app).await {
                tracing::warn!("hints: {e:#}");
            }
            tokio::time::sleep(Duration::from_secs(30)).await;
        }
    });
}
