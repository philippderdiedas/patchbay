//! UI translations. English is the source language and the lookup key;
//! other languages map the English text to a translation (missing entries fall back to English).

use std::{collections::HashMap, sync::LazyLock};

use axum::http::HeaderMap;
use axum_extra::extract::cookie::CookieJar;

pub const LANG_COOKIE: &str = "pbx_lang";

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    De,
}

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::De => "de",
        }
    }

    pub fn parse(s: &str) -> Option<Lang> {
        match s {
            "en" => Some(Lang::En),
            "de" => Some(Lang::De),
            _ => None,
        }
    }

    /// Cookie first, then the browser's Accept-Language, then English.
    pub fn from_headers(headers: &HeaderMap) -> Lang {
        let jar = CookieJar::from_headers(headers);
        if let Some(l) = jar.get(LANG_COOKIE).and_then(|c| Lang::parse(c.value())) {
            return l;
        }
        let accept = headers.get("accept-language").and_then(|v| v.to_str().ok()).unwrap_or("");
        for part in accept.split(',') {
            let tag = part.split(';').next().unwrap_or("").trim().to_lowercase();
            if tag.starts_with("de") {
                return Lang::De;
            }
            if tag.starts_with("en") {
                return Lang::En;
            }
        }
        Lang::En
    }
}

/// Translator handed to templates as `c.t`.
#[derive(Clone, Copy)]
pub struct Tr(pub Lang);

impl Tr {
    pub fn s<'a>(&self, en: &'a str) -> &'a str {
        match self.0 {
            Lang::En => en,
            Lang::De => DE.get(en).copied().unwrap_or(en),
        }
    }
}

